// Bundles the worklet wrappers and the pure cores they use into two self-contained
// scripts (AudioWorklet modules cannot import from a Blob URL).
// Outputs: dist/worklets/{player,capture}.js and src/generated/worklet-sources.ts (committed).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const bundles = {
  player: ['src/errors.ts', 'src/playback-core.ts', 'src/worklets/player.worklet.ts'],
  capture: ['src/errors.ts', 'src/pcm.ts', 'src/resample.ts', 'src/capture-core.ts', 'src/worklets/capture.worklet.ts'],
};

function toPlainJs(file) {
  const ts = readFileSync(path.join(root, file), 'utf8');
  let js = stripTypeScriptTypes(ts, { mode: 'strip' });
  js = js.replace(/^import[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*$/gm, '');
  js = js.replace(/^export\s+/gm, '');
  return `// ---- ${file}\n${js.trim()}\n`;
}

const sources = {};
for (const [name, files] of Object.entries(bundles)) {
  sources[name] = `// bargein ${name} worklet (generated by scripts/build-worklets.mjs)\n` + files.map(toPlainJs).join('\n');
  mkdirSync(path.join(root, 'dist/worklets'), { recursive: true });
  writeFileSync(path.join(root, `dist/worklets/${name}.js`), sources[name]);
}

mkdirSync(path.join(root, 'src/generated'), { recursive: true });
writeFileSync(
  path.join(root, 'src/generated/worklet-sources.ts'),
  '// Generated by scripts/build-worklets.mjs. Do not edit; run `npm run build:worklets`.\n' +
    Object.entries(sources).map(([n, s]) => `export const ${n}WorkletSource: string = ${JSON.stringify(s)};\n`).join(''),
);
console.log('worklets built:', Object.keys(sources).join(', '));
